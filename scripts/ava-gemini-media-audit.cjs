'use strict';
// Verify the legacy-inbox media contract using real routes and isolated SQLite.
// Authentication is an explicit fixture actor; this tests feature gating, not authentication.
const path = require('node:path'), fs = require('node:fs'), assert = require('node:assert/strict');
process.env.NODE_ENV = 'test';
const target = path.resolve(process.argv[2]);
const load = name => require(path.join(target, 'whatsapp_crm', name));
const express = load('node_modules/express');
const DB = load('src/services/database.service');
const Media = load('src/services/whatsapp-media.service');
const Identity = load('src/services/identity/identity-store');
let server;
(async () => {
    load('tests/test-helper').createTestDB(); Identity.ensureSchema();
    const business = await DB.createInstance({ name: 'Media contract audit' });
    await DB.updateInstance(business.id, { isActive: 1, aiProvider: 'gemini', openWaSessionId: 'audit-session' });
    const chatId = '79990000001@c.us';
    await DB.getOrCreateClient(business.id, chatId, 'Synthetic client');
    await DB.saveMessage(business.id, chatId, 'Synthetic client', 'Голосовое сообщение', 'user', null, 'audit-media');
    Media.record({ businessId: business.id, chatId, providerMessageId: 'audit-media', kind: 'audio', provider: 'openwa', sessionId: 'audit-session' });
    DB.run("UPDATE whatsapp_media_inputs SET status='failed',errorCode='AI_TIMEOUT'");
    DB.run("INSERT INTO ava_users(id,subject,email) VALUES('audit-owner','audit-owner','owner@example.test')");
    DB.run("INSERT INTO ava_business_memberships(userId,businessId,role) VALUES('audit-owner',?,'hotel_owner')", [business.id]);
    const actor = Identity.actor('audit-owner');
    load('src/services/ava-release-flags.service').update(actor, business.id, { revision: 0, flags: { workspace: false } });
    let providerCalls = 0;
    const image = await load('node_modules/sharp')({create:{width:10,height:10,channels:3,background:'#fff'}}).png().toBuffer();
    load('src/services/openwa.service').downloadMessageMedia = async () => { providerCalls++; return {buffer:image,mimeType:'image/png'}; };
    load('src/services/gemini-text.service').complete = async () => JSON.stringify({text:'Распознанное вложение'});
    DB.run("UPDATE whatsapp_media_inputs SET kind='image'");
    const app = express(); app.use(express.json());
    app.use((req, _res, next) => { req.auth = actor; next(); });
    app.use('/api', load('src/routes/api.routes'));
    app.use('/api', load('src/routes/ava-workspace.routes'));
    server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
    const origin = 'http://127.0.0.1:' + server.address().port;
    process.env.WHATSAPP_CRM_PUBLIC_URL = origin;
    const messages = await fetch(`${origin}/api/messages/${business.id}/${encodeURIComponent(chatId)}`).then(response => response.json());
    const message = messages.messages[0];
    assert.equal(message.media.canRetry, true);
    const response = await fetch(origin + message.media.mediaUrl + '/retry', { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body: '{}' });
    const body = await response.json();
    assert.equal(response.status, 200); assert.equal(body.success, true); assert.equal(providerCalls, 1);
    assert.equal(Media.get(business.id,chatId,'audit-media').status,'ready');
    const preview=await fetch(origin+message.media.mediaUrl);assert.equal(preview.status,200);assert.equal(preview.headers.get('content-type'),'image/jpeg');
    const result = { verdict: 'PASS', scenario: 'legacy inbox retry and preview work while workspace=false', legacyMessageResponse: { canRetry: message.media.canRetry, hasPreviewUrl: Boolean(message.media.mediaUrl) }, retryResponse: { status: response.status, code: body.code }, providerCalls, boundary: 'Real routes + isolated SQLite; fixture actor. No provider/customer/production actions.' };
    if (process.argv[3]) fs.writeFileSync(process.argv[3], JSON.stringify(result, null, 2) + '\n');
    console.log(JSON.stringify(result));
})().catch(error => { console.error(error.stack); process.exitCode = 1; }).finally(async () => { if (server) await new Promise(resolve => server.close(resolve)); DB.db?.close(); });
