def require(value, code):
    if not value:
        raise RuntimeError(code)


def sha(value):
    return hashlib.sha256(value).hexdigest()


def file_sha(path):
    return sha(Path(path).read_bytes())


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':')).encode()


def relative(name):
    require(isinstance(name, str) and name and not name.startswith('/') and
            all(x not in ('', '.', '..') and not x.startswith('._') for x in name.split('/')) and
            not any(x in name for x in ('\\', '\n', '\r', '\0')), 'UNSAFE_PATH')
    return PurePosixPath(name)


def tree(root):
    root = Path(root)
    require(root.is_dir() and not root.is_symlink(), 'TREE_NOT_DIRECTORY')
    result = {}
    for path in sorted(root.rglob('*')):
        relative(str(path.relative_to(root)))
        require(not path.is_symlink(), 'TREE_SYMLINK_FORBIDDEN')
        if path.is_file():
            result[str(path.relative_to(root))] = file_sha(path)
        else:
            require(path.is_dir(), 'TREE_SPECIAL_FILE')
    return result


def private_json(path, value):
    path = Path(path)
    with tempfile.NamedTemporaryFile(mode='w', dir=path.parent, prefix='.' + path.name, delete=False) as stream:
        temporary = Path(stream.name)
        json.dump(value, stream, indent=2, sort_keys=True)
        stream.write('\n'); stream.flush(); os.fsync(stream.fileno())
    temporary.chmod(0o600)
    os.replace(temporary, path)


def run(command, **kwargs):
    result = subprocess.run(command, capture_output=True, timeout=kwargs.pop('timeout', 180), **kwargs)
    require(result.returncode == 0, 'COMMAND_FAILED')
    return result.stdout


def git(repo, *arguments):
    return run(['git', '-C', str(repo), *arguments])


def commit(repo, ref):
    result = git(repo, 'rev-parse', '--verify', ref + '^{commit}').decode().strip()
    require(re.fullmatch('[0-9a-f]{40}', result), 'COMMIT_REQUIRED')
    return result


def blob(repo, ref, name, optional=False):
    relative(name)
    process = subprocess.run(['git', '-C', str(repo), 'show', ref + ':' + name], capture_output=True)
    if process.returncode and optional:
        return None
    require(process.returncode == 0, 'COMMITTED_FILE_MISSING')
    return process.stdout


