def validate_manifest(m):
    require(m.get('kind') == 'customer-completion-20261018' and m.get('baseCommit') == BASE and
            re.fullmatch('[0-9a-f]{40}', m.get('candidateCommit', '')) and
            set(m.get('services', {})) == set(NAMES), 'MANIFEST_CONTRACT_INVALID')
    for role, item in m['services'].items():
        require(item['baseImage'] == IMAGES[role] and item.get('files') and
                set(item['files']) == set(item.get('baseFiles', {})), 'SERVICE_CONTRACT_INVALID')
        require(re.fullmatch('ava-customer-completion-' + role + r':[a-f0-9-]+', item.get('candidateTag', '')), 'TAG_INVALID')
        for name, digest in item['files'].items():
            relative(name)
            require(re.fullmatch('[0-9a-f]{64}', digest) and
                    (item['baseFiles'][name] is None or re.fullmatch('[0-9a-f]{64}', item['baseFiles'][name])), 'FILE_HASH_INVALID')
            require(name not in ('package.json', 'package-lock.json') and
                    not name.startswith('node_modules/'), 'PRODUCTION_DEPENDENCY_OVERWRITE_FORBIDDEN')
    return m
