def excluded_mounts(row):
    result = []
    for mount in row['Mounts']:
        target = mount['Destination']
        require(target != '/app' and not '/app'.startswith(target.rstrip('/') + '/'), 'APP_MOUNT_FORBIDDEN')
        if target.startswith('/app/'):
            rel = target.removeprefix('/app/')
            require(rel in {'data', 'config', 'voice-config', 'logs', 'output', 'uploads', 'recordings',
                            'main.py', 'models', 'scripts', 'project', 'project/secrets',
                            'project/asterisk_media', 'project/data'},
                    'UNREVIEWED_APP_MOUNT')
            result.append(rel)
    return sorted(result)


def hashes(command, role, target, excluded, image=False):
    executable = ['node', '-e', HASH_JS] if role in ('crm', 'worker') else ['python', '-c', HASH_PY]
    prefix = ['docker', 'run', '--rm', '--network', 'none', '--read-only', '--entrypoint', executable[0], target] if image else ['docker', 'exec', target, executable[0]]
    return json.loads(command(prefix + executable[1:] + [json.dumps(excluded)], timeout=600))


