"""Additive external SIP ownership/rendering. No shell or provider purchase API."""
import hashlib
import ipaddress
import json
import os
from pathlib import Path
import re
import socket
import urllib.request
from urllib.parse import urlsplit

UUID = re.compile(r'[a-f0-9]{8}(?:-[a-f0-9]{4}){3}-[a-f0-9]{12}')
HEADER = '; Generated by AVA external SIP v1.\n'


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *_args, **_kwargs):
        raise ValueError('crm_redirect_refused')


def owner(phone_id, active=False):
    if not isinstance(phone_id, str) or not UUID.fullmatch(phone_id):
        raise ValueError('invalid_phone')
    parsed = urlsplit(os.environ['AVA_TELEPHONY_CRM_URL'].rstrip('/'))
    if parsed.scheme != 'http' or parsed.hostname != '127.0.0.1' or not parsed.port or parsed.username or parsed.password or parsed.path or parsed.query or parsed.fragment:
        raise ValueError('crm_must_be_loopback')
    request = urllib.request.Request(parsed.geturl() + '/api/internal/telephony/external/' + phone_id + ('?active=true' if active else ''),
                                     headers={'Authorization': 'Bearer ' + os.environ['CRM_SERVICE_API_TOKEN']})
    with urllib.request.build_opener(NoRedirect()).open(request, timeout=0.8) as response:
        result = json.loads(response.read(16385))
    if not isinstance(result, dict) or result.get('success') is not True or result.get('phoneId') != phone_id or type(result.get('businessId')) is not int or result['businessId'] < 1:
        raise ValueError('owner_unavailable')
    if result.get('endpoint') != 'ava-phone-' + phone_id.replace('-', '') or not re.fullmatch(r'7\d{10}', str(result.get('number', ''))) or type(result.get('revision')) is not int or result['revision'] < 1:
        raise ValueError('owner_invalid')
    return result


def route(phone_id):
    row = owner(phone_id, active=True)
    return f'{row["businessId"]}|{row["phoneId"]}|{row["number"]}|{row["revision"]}'


def root():
    return Path(os.environ.get('AVA_TELEPHONY_EXTERNAL_DIR', '/etc/asterisk/ava-external'))


def transports(cli):
    try:
        configured = json.loads(os.environ.get('AVA_TELEPHONY_EXTERNAL_TRANSPORTS', '{}'))
    except Exception:
        return {}
    if not isinstance(configured, dict):
        return {}
    result = {}
    for protocol, name in configured.items():
        if protocol not in ('udp', 'tcp', 'tls') or not isinstance(name, str) or not re.fullmatch(r'[a-zA-Z0-9_-]{1,60}', name):
            continue
        try:
            output = cli('pjsip show transport ' + name)
            if not re.search(r'protocol\s*:\s*' + protocol + r'\b', output, re.I):
                continue
            if protocol == 'tls' and not re.search(r'verify_server\s*:\s*(?:yes|true)\b', output, re.I):
                continue
            result[protocol] = name
        except Exception:
            pass
    return result


def capabilities(cli):
    available = False
    choices = {}
    try:
        marker = json.loads((root() / 'install.json').read_text())
        if os.environ.get('AVA_TELEPHONY_EXTERNAL_SIP_ENABLED') == 'true' and marker.get('version') == 1 and (root() / 'pjsip').is_dir() and (root() / 'dialplan').is_dir():
            choices = transports(cli)
            available = bool(choices) and 'asterisk-ai-voice-agent' in cli('ari show apps') and 'MixMonitor' in cli('core show application MixMonitor')
    except Exception:
        pass
    return {'success': True, 'available': available, 'transports': sorted(choices) if available else []}


def public_ip(value):
    try:
        address = ipaddress.ip_address(value)
        if not address.is_global or address.is_multicast or address.is_reserved or getattr(address, 'ipv4_mapped', None):
            return False
        if address.version == 6:
            return address in ipaddress.ip_network('2000::/3') and not any(address in ipaddress.ip_network(network) for network in ('2001::/23', '2001:db8::/32', '2002::/16', '3fff::/20'))
        return True
    except Exception:
        return False


def scope(data):
    if not isinstance(data, dict) or not isinstance(data.get('phoneId'), str) or not UUID.fullmatch(data['phoneId']):
        raise ValueError('invalid_phone')
    if data.get('endpoint') != 'ava-phone-' + data['phoneId'].replace('-', '') or type(data.get('businessId')) is not int or data['businessId'] < 1 or type(data.get('revision')) is not int or data['revision'] < 1:
        raise ValueError('invalid_scope')
    current = owner(data['phoneId'])
    if current['businessId'] != data['businessId'] or current['endpoint'] != data['endpoint'] or current['revision'] != data['revision']:
        raise ValueError('owner_changed')
    return current


def render(data, cli):
    current = scope(data)
    credentials = data.get('credentials')
    if not isinstance(credentials, dict) or current.get('businessActive') is not True or current['number'] != data.get('number') or current.get('state') not in ('active', 'provisioning'):
        raise ValueError('invalid_payload')
    login, password, host = (credentials.get(key) for key in ('login', 'password', 'host'))
    port, protocol = credentials.get('port'), credentials.get('transport')
    if not isinstance(login, str) or not re.fullmatch(r'[a-zA-Z0-9_.+~-]{1,80}', login) or not isinstance(password, str) or not re.fullmatch(r'[a-zA-Z0-9_.!@#$%&*+=:?~\-]{1,128}', password):
        raise ValueError('invalid_credentials')
    if not isinstance(host, str) or len(host) > 253 or type(port) is not int or not 1 <= port <= 65535 or protocol not in transports(cli):
        raise ValueError('invalid_server')
    try:
        ipaddress.ip_address(host)
        resolved = [host]
    except ValueError:
        if not re.fullmatch(r'(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z][a-z0-9-]{1,62}', host) or re.search(r'\.(?:local|localhost|internal|test|invalid|example)$', host):
            raise ValueError('invalid_host')
        resolved = sorted({item[4][0] for item in socket.getaddrinfo(host, port, type=socket.SOCK_STREAM)})
    pinned = credentials.get('addresses')
    if not isinstance(pinned, list) or not pinned or len(pinned) > 32 or any(not isinstance(ip, str) or not public_ip(ip) for ip in pinned) or any(not public_ip(ip) for ip in resolved) or set(resolved) != set(pinned):
        raise ValueError('public_address_changed')
    fingerprint = credentials.get('fingerprint')
    if not isinstance(fingerprint, str) or not re.fullmatch(r'[a-f0-9]{64}', fingerprint):
        raise ValueError('invalid_fingerprint')
    name, phone, business, revision = data['endpoint'], data['number'], data['businessId'], data['revision']
    context = 'ava-ext-' + data['phoneId'].replace('-', '')
    address = sorted(pinned)[0]
    server = f'[{host}]' if ':' in host else host
    pinned_host = f'[{address}]' if ':' in address else address
    scheme = 'sips' if protocol == 'tls' else 'sip'
    uri = f'{scheme}:{server}:{port}'
    proxy = f'{scheme}:{pinned_host}:{port}\\;transport={protocol}\\;lr'
    permit = ''.join(f'permit={ip}/{128 if ":" in ip else 32}\n' for ip in sorted(pinned))
    pjsip = HEADER + f'''[{name}-auth]
type=auth
auth_type=userpass
username={login}
password={password}

[{name}-aor]
type=aor
contact={uri}

[{name}]
type=endpoint
transport={transports(cli)[protocol]}
context={context}
disallow=all
allow=alaw,ulaw
outbound_auth={name}-auth
aors={name}-aor
outbound_proxy={proxy}
from_user={login}
from_domain={host}
callerid={phone}
direct_media=no
rtp_symmetric=yes
force_rport=yes
rewrite_contact=yes
dtmf_mode=rfc4733
deny=0.0.0.0/0
deny=::/0
{permit}
[{name}-reg]
type=registration
transport={transports(cli)[protocol]}
outbound_auth={name}-auth
server_uri={uri}
client_uri={scheme}:{login}@{server}:{port}
outbound_proxy={proxy}
contact_user={phone}
line=yes
endpoint={name}
retry_interval=60
forbidden_retry_interval=600
expiration=300
'''
    expected = f'{business}|{data["phoneId"]}|{phone}|{revision}'
    dialplan = HEADER + f'''[{context}]
exten => s,1,Goto({context},verify,1)
exten => _.,1,Goto({context},verify,1)
exten => verify,1,Set(CURLOPT(conntimeout)=1)
 same => n,Set(CURLOPT(httptimeout)=1)
 same => n,Set(AVA_EXT_ROUTE=${{CURL(http://127.0.0.1:8097/external-resolve/{data['phoneId']})}})
 same => n,GotoIf($["${{AVA_EXT_ROUTE}}"!="{expected}"]?reject)
 same => n,Set(__AAVA_MANAGED_INGRESS=1)
 same => n,Set(__AAVA_BUSINESS_ID={business})
 same => n,Set(__AAVA_INSTANCE_ID={business})
 same => n,Set(__AAVA_PHONE_ID={data['phoneId']})
 same => n,Set(__FROM_DID={phone})
 same => n,Set(DIALED_NUMBER={phone})
 same => n,GotoIf($[${{REGEX("^[a-zA-Z0-9_.-]+$" ${{UNIQUEID}})}}=0]?reject)
 same => n,MixMonitor(/var/spool/asterisk/monitor/ava-{business}-${{UNIQUEID}}.wav,i(AAVA_MIXMONITOR_ID))
 same => n,GotoIf($["${{AAVA_MIXMONITOR_ID}}"=""]?reject)
 same => n,Set(__AAVA_RECORDING_STARTED=1)
 same => n,Progress()
 same => n,Stasis(asterisk-ai-voice-agent)
 same => n,Hangup()
 same => n(reject),Hangup(21)
'''
    metadata = {'phoneId': data['phoneId'], 'businessId': business, 'endpoint': name, 'number': phone, 'revision': revision,
                'fingerprint': fingerprint, 'context': context, 'serverUri': uri,
                'pjsipHash': hashlib.sha256(pjsip.encode()).hexdigest(), 'dialplanHash': hashlib.sha256(dialplan.encode()).hexdigest()}
    return pjsip, dialplan, metadata


def paths(data):
    name = data['endpoint']
    return root() / 'pjsip' / (name + '.conf'), root() / 'dialplan' / (name + '.conf'), root() / (name + '.json')


def read_owned(data):
    files = paths(data)
    if any(path.is_symlink() for path in files):
        raise ValueError('invalid_path')
    if not any(path.exists() for path in files):
        return None
    if not all(path.is_file() for path in files):
        raise ValueError('partial_config')
    metadata = json.loads(files[2].read_text())
    if metadata.get('phoneId') != data['phoneId'] or metadata.get('businessId') != data['businessId'] or metadata.get('endpoint') != data['endpoint']:
        raise ValueError('unowned_config')
    for index, key in ((0, 'pjsipHash'), (1, 'dialplanHash')):
        content = files[index].read_text()
        if not content.startswith(HEADER) or hashlib.sha256(content.encode()).hexdigest() != metadata.get(key):
            raise ValueError('config_changed')
    return metadata


def status(data, cli):
    scope(data)
    metadata = read_owned(data)
    if metadata is None:
        runtime = cli('pjsip show endpoint ' + data['endpoint'])
        if data['endpoint'] in runtime and 'Unable to find' not in runtime:
            raise ValueError('orphaned_runtime_requires_reconciliation')
        return {'success': True, 'configured': False, 'registered': False, 'revision': 0}
    endpoint = cli('pjsip show endpoint ' + data['endpoint'])
    dialplan = cli('dialplan show ' + metadata['context'])
    registration = cli('pjsip show registration ' + data['endpoint'] + '-reg')
    loaded = bool(re.search(r'context\s*:\s*' + re.escape(metadata['context']) + r'\b', endpoint)) and 'AVA_EXT_ROUTE' in dialplan and metadata['serverUri'] in registration
    return {'success': True, 'configured': loaded, 'registered': loaded and bool(re.search(r'\bRegistered\b', registration)),
            'revision': metadata['revision'], 'fingerprint': metadata['fingerprint']}


def manage(data, cli, atomic, lock, remove=False):
    scope(data)
    if not capabilities(cli)['available']:
        raise ValueError('external_host_not_ready')
    with lock:
        if any('!' in line for line in cli('core show channels concise').splitlines()):
            raise ValueError('active_calls')
        previous = read_owned(data)
        if previous and previous['revision'] > data['revision']:
            raise ValueError('newer_config')
        files = paths(data)
        old = [path.read_text() if path.exists() else None for path in files]
        if remove and previous is None:
            # Absence on disk is not proof that no endpoint remains in memory.
            status(data, cli)
            return {'success': True}
        new = render(data, cli) if not remove else None
        if not remove and previous and previous['revision'] == data['revision'] and previous['fingerprint'] != new[2]['fingerprint']:
            raise ValueError('revision_conflict')
        try:
            for path, content in zip(files, old):
                if content is not None:
                    atomic(path.with_suffix('.previous'), content)
            for path, content in zip(files, (new[0], new[1], json.dumps(new[2], sort_keys=True)) if new else (None, None, None)):
                if content is None:
                    path.unlink(missing_ok=True)
                else:
                    atomic(path, content)
            cli('pjsip reload')
            cli('dialplan reload')
            output = cli('pjsip show endpoint ' + data['endpoint'])
            if not remove and not re.search(r'context\s*:\s*' + re.escape(new[2]['context']) + r'\b', output):
                raise ValueError('endpoint_not_loaded')
            if remove and data['endpoint'] in output and 'Unable to find' not in output:
                raise ValueError('endpoint_still_loaded')
        except Exception:
            for path, content in zip(files, old):
                if content is None:
                    path.unlink(missing_ok=True)
                else:
                    atomic(path, content)
            cli('pjsip reload')
            cli('dialplan reload')
            raise
    return {'success': True}


def handle(path, data, cli, atomic, lock):
    if path == '/external/capabilities':
        return capabilities(cli)
    if path == '/external/status':
        return status(data, cli)
    if path in ('/external/apply', '/external/remove'):
        return manage(data, cli, atomic, lock, remove=path.endswith('/remove'))
    raise ValueError('unknown_action')
