#!/usr/bin/env python3
"""Narrow host service for AVA-generated PJSIP files. No shell or caller-selected paths."""
import hmac
import importlib.util
import http.server
import json
import os
from pathlib import Path
import re
import socketserver
import subprocess
import tempfile
import threading
import urllib.request
from urllib.parse import urlsplit

LOCK = threading.Lock()
ENDPOINT = re.compile(r"ava-phone-[a-f0-9]{32}")
RECORDING_DIR = Path('/var/spool/asterisk/monitor')


def external_module():
    spec = importlib.util.spec_from_file_location('ava_external_sip', Path(__file__).with_name('external_sip.py'))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def cli(command):
    result = subprocess.run([os.environ.get("AVA_ASTERISK_BIN", "/usr/sbin/asterisk"), "-rx", command],
                            capture_output=True, text=True, timeout=10, check=True)
    if re.search(r"No such command|Unable to connect|Error parsing|Could not reload", result.stdout + result.stderr, re.I):
        raise ValueError("asterisk_refused")
    return result.stdout


def endpoint(value):
    if not isinstance(value, str) or not ENDPOINT.fullmatch(value):
        raise ValueError("invalid_endpoint")
    return value


def render(data):
    if not isinstance(data, dict) or not isinstance(data.get('credentials'), dict):
        raise ValueError('invalid_payload')
    name = endpoint(data.get("endpoint"))
    phone_id = data.get("phoneId", "")
    if not isinstance(phone_id, str) or not re.fullmatch(r'[a-f0-9]{8}(?:-[a-f0-9]{4}){3}-[a-f0-9]{12}', phone_id):
        raise ValueError('invalid_phone')
    if name != "ava-phone-" + phone_id.replace("-", ""):
        raise ValueError("invalid_scope")
    number = str(data.get("number", ""))
    credentials = data.get("credentials", {})
    login, password, domain = (credentials.get(k, "") for k in ("login", "password", "domain"))
    if not all(isinstance(value, str) for value in (login, password, domain)):
        raise ValueError('invalid_credentials')
    domains = os.environ.get("AVA_TELEPHONY_SIP_DOMAINS", "sip.exolve.ru").split(",")
    if not re.fullmatch(r"7\d{10}", number) or not re.fullmatch(r"\d{8,20}", login):
        raise ValueError("invalid_identity")
    if domain not in domains or not re.fullmatch(r"[a-zA-Z0-9.-]+", domain):
        raise ValueError("invalid_domain")
    if not re.fullmatch(r"[a-zA-Z0-9_.!@#$%&*+=:?~\-]{1,128}", password):
        raise ValueError("invalid_password_format")
    transport = os.environ.get("AVA_TELEPHONY_TRANSPORT", "transport-udp")
    if not re.fullmatch(r"[\w-]{1,60}", transport):
        raise ValueError("invalid_transport")
    return f"""; Generated by AVA. Only this resource may be changed by the agent.
[{name}-auth]
type=auth
auth_type=userpass
username={login}
password={password}

[{name}-aor]
type=aor
contact=sip:{domain}
qualify_frequency=60

[{name}]
type=endpoint
transport={transport}
context=ava-managed-sip-reject
disallow=all
allow=alaw,ulaw
outbound_auth={name}-auth
aors={name}-aor
from_user={login}
from_domain={domain}
callerid={number}
send_pai=yes
trust_id_outbound=yes
direct_media=no
rtp_symmetric=yes
force_rport=yes
rewrite_contact=yes
dtmf_mode=rfc4733

[{name}-reg]
type=registration
transport={transport}
outbound_auth={name}-auth
server_uri=sip:{domain}
client_uri=sip:{login}@{domain}
contact_user={login}
retry_interval=60
forbidden_retry_interval=600
expiration=300
"""


def atomic(path, content):
    fd, temporary = tempfile.mkstemp(prefix=".ava-", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as file:
            file.write(content)
            file.flush()
            os.fsync(file.fileno())
        os.chmod(temporary, 0o600)
        os.replace(temporary, path)
        directory_fd = os.open(path.parent, os.O_RDONLY)
        try:
            os.fsync(directory_fd)
        finally:
            os.close(directory_fd)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def manage(data, remove=False):
    if not isinstance(data, dict):
        raise ValueError('invalid_payload')
    name = endpoint(data.get("endpoint"))
    directory = Path(os.environ.get("AVA_TELEPHONY_CONFIG_DIR", "/etc/asterisk/ava-managed"))
    directory.mkdir(mode=0o700, parents=True, exist_ok=True)
    path = directory / (name + ".conf")
    with LOCK:
        if path.is_symlink():
            raise ValueError("invalid_path")
        previous = path.read_text() if path.exists() else None
        if remove:
            if previous is None:
                return {"success": True}
            if not previous.startswith("; Generated by AVA."):
                raise ValueError("unowned_config")
            atomic(directory / (name + ".previous"), previous)
            path.unlink()
        else:
            content = render(data)
            if previous is not None:
                if not previous.startswith("; Generated by AVA."):
                    raise ValueError("unowned_config")
                atomic(directory / (name + ".previous"), previous)
            atomic(path, content)
        try:
            cli("pjsip reload")
            if not remove:
                output = cli("pjsip show endpoint " + name)
                if name not in output or "Unable to find" in output:
                    raise ValueError("endpoint_not_loaded")
            else:
                output = cli("pjsip show endpoint " + name)
                if name in output and "Unable to find" not in output:
                    raise ValueError("endpoint_still_loaded")
        except Exception:
            if previous is None:
                path.unlink(missing_ok=True)
            else:
                atomic(path, previous)
            cli("pjsip reload")
            raise
    return {"success": True}


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *_args, **_kwargs):
        raise ValueError('crm_redirect_refused')


def resolve(number):
    if not re.fullmatch(r"\+?[78]?\d{10}", number):
        raise ValueError("invalid_did")
    base = os.environ["AVA_TELEPHONY_CRM_URL"].rstrip("/")
    parsed = urlsplit(base)
    if (parsed.scheme != 'http' or parsed.hostname != '127.0.0.1' or not parsed.port
            or parsed.username or parsed.password or parsed.path or parsed.query or parsed.fragment):
        raise ValueError("crm_must_be_loopback")
    req = urllib.request.Request(base + "/api/internal/telephony/resolve/" + number,
                                 headers={"Authorization": "Bearer " + os.environ["CRM_SERVICE_API_TOKEN"]})
    with urllib.request.build_opener(NoRedirect()).open(req, timeout=0.8) as response:
        result = json.loads(response.read(16385))
    if (not isinstance(result, dict) or result.get("success") is not True
            or type(result.get("businessId")) is not int or result['businessId'] < 1):
        raise ValueError("did_unavailable")
    phone = result.get("phoneId") or "legacy"
    if phone == 'legacy' and result.get('legacy') is not True:
        raise ValueError('invalid_phone')
    if not isinstance(phone, str) or not re.fullmatch(r"[a-f0-9]{8}(?:-[a-f0-9]{4}){3}-[a-f0-9]{12}|legacy", phone):
        raise ValueError("invalid_phone")
    normalized = number.lstrip('+')
    normalized = '7' + normalized[1:] if normalized.startswith('8') and len(normalized) == 11 else normalized
    normalized = '7' + normalized if len(normalized) == 10 else normalized
    if not isinstance(result.get('number'), str) or result['number'] != normalized or not re.fullmatch(r"7\d{10}", result.get("number", "")):
        raise ValueError("invalid_number")
    return f'{result["businessId"]}|{phone}|{result["number"]}'


class Handler(http.server.BaseHTTPRequestHandler):
    def setup(self):
        super().setup()
        self.connection.settimeout(5)

    server_version = "AVA-Telephony"

    def log_message(self, *_):
        pass  # Requests contain credentials; emit bounded events only.

    def send(self, status, body, content_type="application/json"):
        encoded = (json.dumps(body) if content_type == "application/json" else body).encode()
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Cache-Control", "no-store")
        self.send_header("Content-Length", str(len(encoded)))
        self.end_headers()
        self.wfile.write(encoded)

    def do_GET(self):
        if getattr(self.server, 'resolver_only', False) and self.path.startswith('/external-resolve/'):
            try:
                return self.send(200, external_module().route(self.path[len('/external-resolve/'):]), 'text/plain')
            except Exception:
                return self.send(404, '', 'text/plain')
        if not getattr(self.server, "resolver_only", False) or not self.path.startswith("/resolve/"):
            return self.send(404, "", "text/plain")
        try:
            return self.send(200, resolve(self.path[len("/resolve/"):]), "text/plain")
        except Exception:
            return self.send(404, "", "text/plain")

    def do_POST(self):
        expected = "Bearer " + os.environ.get("AVA_TELEPHONY_AGENT_TOKEN", "")
        if getattr(self.server, "resolver_only", False) or len(expected) < 40 or not hmac.compare_digest(self.headers.get("Authorization", ""), expected):
            return self.send(403, {"success": False})
        try:
            if self.headers.get('Transfer-Encoding'):
                raise ValueError('unsupported_encoding')
            length = int(self.headers.get("Content-Length", "0"))
            if length < 0 or length > 8192:
                raise ValueError("body_too_large")
            data = json.loads(self.rfile.read(length) or b"{}")
            if not isinstance(data, dict):
                raise ValueError('invalid_payload')
            if self.path.startswith('/external/'):
                result = external_module().handle(self.path, data, cli, atomic, LOCK)
            elif self.path == "/apply":
                result = manage(data)
            elif self.path == "/remove":
                result = manage(data, remove=True)
            elif self.path == "/status":
                output = cli("pjsip show registration " + endpoint(data.get("endpoint")) + "-reg")
                result = {"success": True, "registered": bool(re.search(r"\bRegistered\b", output))}
            elif self.path == "/calls":
                output = cli("core show channels concise")
                result = {"success": True, "active": sum("!" in line for line in output.splitlines())}
            elif self.path == "/health":
                output = cli("dialplan show ava-exolve-managed")
                transport = os.environ.get("AVA_TELEPHONY_TRANSPORT", "transport-udp")
                ingress = os.environ.get("AVA_TELEPHONY_EXOLVE_ENDPOINT", "")
                if not re.fullmatch(r"[a-zA-Z0-9_.-]{1,80}", ingress):
                    raise ValueError("ingress_endpoint_required")
                ingress_config = cli("pjsip show endpoint " + ingress)
                if not re.fullmatch(r'[a-zA-Z0-9_-]{1,60}', transport):
                    raise ValueError('invalid_transport')
                present = bool(re.search(r'(?<![\w-])' + re.escape(transport) + r'(?![\w-])', cli("pjsip show transports")))
                app_ready = 'asterisk-ai-voice-agent' in cli('ari show apps')
                # ProtectSystem makes this path read-only in the agent namespace.
                # Actual Asterisk write access and a finalized WAV are canary gates.
                recording_ready = (RECORDING_DIR.is_dir()
                                   and 'MixMonitor' in cli('core show application MixMonitor')
                                   and 'AAVA_RECORDING_STARTED' in cli('dialplan show ava-managed-record')
                                   and 'outbound_recorded' in cli('dialplan show ava-managed-outbound-record'))
                # Operator sets the gate only after the existing ingress points to this context.
                result = {"success": True, "recordingReady": recording_ready,
                          "ingressReady": recording_ready and "AAVA_MANAGED_INGRESS" in cli('dialplan show ava-managed-resolve') and 'ava-managed-resolve' in output
                          and 'asterisk-ai-voice-agent' in cli('dialplan show ava-managed-resolve') and present and app_ready
                          and bool(re.search(r"context\s*:\s*ava-exolve-managed\b", ingress_config))
                          and os.environ.get("AVA_TELEPHONY_INGRESS_VERIFIED") == "true"}
            else:
                return self.send(404, {"success": False})
            return self.send(200, result)
        except Exception:
            return self.send(503, {"success": False, "code": "TELEPHONY_AGENT_OPERATION_FAILED"})


class UnixServer(socketserver.ThreadingMixIn, socketserver.UnixStreamServer):
    daemon_threads = True


def main():
    socket_path = Path(os.environ.get("AVA_TELEPHONY_AGENT_SOCKET", "/run/ava-telephony/agent.sock"))
    socket_path.parent.mkdir(mode=0o750, parents=True, exist_ok=True)
    # systemd owns the directory; never unlink an active socket silently.
    if socket_path.exists():
        raise RuntimeError("agent_socket_already_exists")
    server = UnixServer(str(socket_path), Handler)
    os.chmod(socket_path, 0o660)
    resolver = http.server.ThreadingHTTPServer(("127.0.0.1", int(os.environ.get("AVA_TELEPHONY_RESOLVER_PORT", "8097"))), Handler)
    resolver.resolver_only = True
    thread = threading.Thread(target=resolver.serve_forever, daemon=True)
    thread.start()
    try:
        server.serve_forever()
    finally:
        server.server_close()
        resolver.shutdown()
        socket_path.unlink(missing_ok=True)


if __name__ == "__main__":
    main()
